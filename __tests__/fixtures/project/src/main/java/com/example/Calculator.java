package com.example;

/**
 * Source file for the mutations in statuses.xml and statuses.csv,
 * the mutated lines match the line numbers in those reports.
 */
public class Calculator {

    public int add(int a, int b) {
        return a + b;
    }

    public int subtract(int a, int b) {
        int result;
        result = a - b;
        return result;
    }

    public int divide(int a, int b) {
        return a / b;
    }
}
